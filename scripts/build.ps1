<#
.SYNOPSIS
  Build the portable-pi USB drive.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\build.ps1 -Target E:\

.EXAMPLE
  # simulated target (CI / dry run), no PortableGit, with a live smoke test
  powershell -File scripts\build.ps1 -Target C:\temp\usb-sim -SkipGit -SmokeTest
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Target,
    [string]$NodeVersion,
    [string]$PiVersion,
    [switch]$SkipGit,
    [switch]$SkipNode,
    [switch]$Force,
    [switch]$SmokeTest
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$RepoRoot = Split-Path -Parent $PSScriptRoot
$ManifestPath = Join-Path $RepoRoot 'manifest.json'
if (-not (Test-Path $ManifestPath)) { throw "manifest.json not found at $ManifestPath" }
$M = Get-Content $ManifestPath -Raw | ConvertFrom-Json

if (-not $NodeVersion) { $NodeVersion = $M.node.version }
if (-not $PiVersion) { $PiVersion = $M.pi.version }

$Staging = Join-Path ([IO.Path]::GetTempPath()) ("portable-pi-build-" + [Guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -ItemType Directory -Force -Path $Staging | Out-Null

function Write-Step([string]$Text) { Write-Host "==> $Text" -ForegroundColor Cyan }
function Write-Warn2([string]$Text) { Write-Host "    ! $Text" -ForegroundColor Yellow }
function Write-Ok([string]$Text) { Write-Host "    $Text" -ForegroundColor DarkGray }

function Invoke-Download([string]$Url, [string]$Dest) {
    if (Test-Path $Dest) { Remove-Item $Dest -Force }
    for ($i = 1; $i -le 3; $i++) {
        try {
            Invoke-WebRequest -Uri $Url -OutFile $Dest -UseBasicParsing -TimeoutSec 300
            return
        } catch {
            if ($i -eq 3) { throw "Download failed: $Url`n$($_.Exception.Message)" }
            Start-Sleep -Seconds (2 * $i)
        }
    }
}

function Get-Sha256([string]$Path) {
    # .NET instead of Get-FileHash: the cmdlet is unavailable in some Windows
    # PowerShell setups where the PS7 module dir shadows the v1.0 modules.
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $fs = [IO.File]::OpenRead($Path)
    try { $hash = $sha.ComputeHash($fs) } finally { $fs.Dispose(); $sha.Dispose() }
    -join ($hash | ForEach-Object { $_.ToString('x2') })
}

function Expand-ArchiveAny([string]$Archive, [string]$Dest) {
    New-Item -ItemType Directory -Force -Path $Dest | Out-Null
    # Must be the Windows bsdtar in System32: a GNU tar from Git-for-Windows on PATH
    # treats "C:\..." as an rsh host spec and fails.
    $tar = Join-Path $env:SystemRoot 'System32\tar.exe'
    if (-not (Test-Path $tar)) { throw "$tar not found. Windows 10 1803+ ships it, or build on Linux with build.sh." }
    & $tar -xf $Archive -C $Dest
    if ($LASTEXITCODE -ne 0) { throw "tar extraction failed for $Archive" }
}

# npm registry tarball URL without needing npm: scoped names are %2f-encoded
function Get-NpmTarballUrl([string]$Name, [string]$Version) {
    if ($Name.StartsWith('@')) {
        $parts = $Name.Split('/', 2)
        $scope = [Uri]::EscapeDataString($parts[0] + '/' + $parts[1])
        $base = $parts[1]
        return "https://registry.npmjs.org/$scope/-/$base-$Version.tgz"
    }
    return "https://registry.npmjs.org/$Name/-/$Name-$Version.tgz"
}

# exFAT has no symlinks: npm/npx/corepack in the linux tarball are symlinks.
# Replace them with portable sh wrappers.
function Set-ShWrapper([string]$BinDir, [string]$Name, [string]$JsRelative) {
    $path = Join-Path $BinDir $Name
    if (Test-Path $path) { Remove-Item $path -Force -Recurse }
    $content = @"
#!/bin/sh
# generated by portable-pi: exFAT has no symlinks
self=`$0
case "`$self" in
  */*) ;;
  *) self=`$(command -v -- "`$self" 2>/dev/null || echo "`$self") ;;
esac
basedir=`$(cd -- "`$(dirname -- "`$self")" && pwd)
exec "`$basedir/node" "`$basedir/$JsRelative" "`$@"
"@
    # LF endings and UTF-8 without BOM, otherwise the kernel refuses to run it
    $bytes = [Text.Encoding]::UTF8.GetBytes(($content -replace "`r`n", "`n"))
    [IO.File]::WriteAllBytes($path, $bytes)
}

# Text files meant for Linux must keep LF endings end-to-end (git on Windows may CRLF them).
function Copy-TextLf([string]$Source, [string]$Dest) {
    $dir = Split-Path -Parent $Dest
    if ($dir -and -not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    $text = [IO.File]::ReadAllText($Source) -replace "`r`n", "`n"
    [IO.File]::WriteAllBytes($Dest, [Text.Encoding]::UTF8.GetBytes($text))
}

# Batch files must be CRLF: cmd.exe misparses LF-only multi-line if/label blocks.
function Copy-TextCrlf([string]$Source, [string]$Dest) {
    $dir = Split-Path -Parent $Dest
    if ($dir -and -not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    $text = ([IO.File]::ReadAllText($Source) -replace "`r`n", "`n") -replace "`n", "`r`n"
    [IO.File]::WriteAllBytes($Dest, [Text.Encoding]::UTF8.GetBytes($text))
}

# exFAT/FAT cannot hold symlinks. The linux node tarball has a few (bin/npm,
# bin/npx, bin/corepack): replace them with the real file before copying out.
function Resolve-ReparsePoints([string]$Root) {
    $links = @(Get-ChildItem $Root -Recurse -Force -ErrorAction SilentlyContinue |
        Where-Object { $_.Attributes -band [IO.FileAttributes]::ReparsePoint })
    foreach ($l in $links) {
        $raw = $l.Target
        if ($raw -is [array]) { $raw = $raw[0] }
        $resolved = if ($raw -and [IO.Path]::IsPathRooted($raw)) { $raw } else { Join-Path $l.DirectoryName $raw }
        $resolved = [IO.Path]::GetFullPath($resolved)
        Remove-Item -LiteralPath $l.FullName -Force -Recurse -ErrorAction SilentlyContinue
        if (Test-Path -LiteralPath $resolved) {
            Copy-Item -LiteralPath $resolved -Destination $l.FullName -Recurse -Force
        }
    }
    if ($links.Count -gt 0) { Write-Ok "$($links.Count) symlink(s) dereferenced for a FAT/exFAT target" }
}

function Copy-Subset([string]$Source, [string]$Dest, [string[]]$Keep) {
    New-Item -ItemType Directory -Force -Path $Dest | Out-Null
    foreach ($entry in $Keep) {
        if ($entry -eq '*') {
            Copy-Item -Path (Join-Path $Source '*') -Destination $Dest -Recurse -Force
        } else {
            $p = Join-Path $Source $entry
            if (-not (Test-Path $p)) { throw "missing '$entry' in $Source" }
            $dst = Join-Path $Dest $entry
            New-Item -ItemType Directory -Force -Path (Split-Path -Parent $dst) | Out-Null
            Copy-Item -Path $p -Destination $dst -Recurse -Force
        }
    }
}

try {
    # ── target ────────────────────────────────────────────────────────────
    if (-not (Test-Path $Target)) { throw "Target '$Target' does not exist. Plug the USB drive in first." }
    $Target = (Resolve-Path $Target).Path.TrimEnd('\', '/')
    Write-Step "Building portable-pi at $Target"
    Write-Ok "node $NodeVersion | pi $PiVersion | git: $(if ($SkipGit) { 'skipped' } else { 'MinGit ' + $M.git.minGit.version })"

    $drive = (Split-Path -Qualifier $Target).TrimEnd(':')
    try {
        $free = (Get-PSDrive -Name $drive -ErrorAction Stop).Free / 1MB
        if ($free -lt 900) { Write-Warn2 ("only {0:N0} MB free, ~700 MB recommended" -f $free) }
    } catch { }

    $out = @{
        NodeWin   = Join-Path $Target ($M.node.targets[0].installDir -replace '\{version\}', $NodeVersion)
        NodeLinux = Join-Path $Target ($M.node.targets[1].installDir -replace '\{version\}', $NodeVersion)
        Runtime   = Join-Path $Target $M.paths.runtimeDir
        Config    = Join-Path $Target $M.paths.agentDir
        Skills    = Join-Path $Target $M.paths.skillsDir
        Temp      = Join-Path $Target $M.paths.tempDir
    }

    # ── node ──────────────────────────────────────────────────────────────
    if (-not $SkipNode) {
        $sums = Join-Path $Staging 'SHASUMS256.txt'
        Invoke-Download ($M.node.checksums -replace '\{version\}', $NodeVersion) $sums
        $sumLines = Get-Content $sums

        foreach ($t in $M.node.targets) {
            $dir = Join-Path $Target ($t.installDir -replace '\{version\}', $NodeVersion)
            $binMarker = Join-Path $dir $t.nodeBin
            if ((Test-Path $binMarker) -and -not $Force) {
                Write-Step "node $($t.id) already present, skipping"
            } else {
                $archiveName = $t.archive -replace '\{version\}', $NodeVersion
                $archive = Join-Path $Staging $archiveName
                Write-Step "Downloading $archiveName"
                Invoke-Download ($t.url -replace '\{version\}', $NodeVersion) $archive

                $expected = $null
                $pattern = '\s' + [regex]::Escape($archiveName) + '$'
                foreach ($line in $sumLines) {
                    if ($line -match $pattern) { $expected = ($line -split '\s+')[0]; break }
                }
                if (-not $expected) { throw "no checksum for $archiveName in SHASUMS256.txt" }
                $actual = Get-Sha256 $archive
                if ($actual -ne $expected.ToLower()) { throw "checksum mismatch for $archiveName (got $actual)" }
                Write-Ok "sha256 ok"

                $extract = Join-Path $Staging "x-$($t.id)"
                Remove-Item $extract -Recurse -Force -ErrorAction SilentlyContinue
                Expand-ArchiveAny $archive $extract
                Resolve-ReparsePoints $extract
                $top = Get-ChildItem $extract -Directory | Select-Object -First 1
                if (-not $top) { throw "unexpected archive layout for $archiveName" }
                Remove-Item $dir -Recurse -Force -ErrorAction SilentlyContinue
                New-Item -ItemType Directory -Force -Path (Split-Path -Parent $dir) | Out-Null
                Move-Item $top.FullName $dir
                Write-Ok "extracted to $dir"
            }

            if ($t.id -eq 'linux-x64') {
                Set-ShWrapper (Join-Path $dir 'bin') 'npm' '../lib/node_modules/npm/bin/npm-cli.js'
                Set-ShWrapper (Join-Path $dir 'bin') 'npx' '../lib/node_modules/npm/bin/npx-cli.js'
                Set-ShWrapper (Join-Path $dir 'bin') 'corepack' '../lib/node_modules/corepack/dist/corepack.js'
                Write-Ok "npm/npx/corepack rewritten as symlink-free sh wrappers"
            }
        }
    } else { Write-Step "node download skipped (-SkipNode)" }

    # ── pi runtime ────────────────────────────────────────────────────────
    $nm = Join-Path $out.Runtime 'node_modules'
    New-Item -ItemType Directory -Force -Path $nm | Out-Null
    $pkgs = @($M.pi.runtimePackages)
    foreach ($o in $M.pi.optionalPackages) { if ($o.enabled) { $pkgs += $o } }

    foreach ($p in $pkgs) {
        $version = $p.version
        if ($p.name -eq '@earendil-works/pi-coding-agent' -and $PiVersion) { $version = $PiVersion }
        $destPkg = Join-Path $nm ($p.name -replace '/', '\')
        if ((Test-Path $destPkg) -and -not $Force) {
            Write-Step "$($p.name) already present, skipping"
            continue
        }
        $url = Get-NpmTarballUrl $p.name $version
        $tgz = Join-Path $Staging (($p.name -replace '[/@]', '_') + ".tgz")
        Write-Step "Downloading $($p.name)@$version"
        Invoke-Download $url $tgz
        $extract = Join-Path $Staging ("x-" + ($p.name -replace '[/@]', '_'))
        Remove-Item $extract -Recurse -Force -ErrorAction SilentlyContinue
        Expand-ArchiveAny $tgz $extract
        $pkgDir = Join-Path $extract 'package'
        if (-not (Test-Path $pkgDir)) { throw "unexpected tarball layout for $($p.name)" }
        Remove-Item $destPkg -Recurse -Force -ErrorAction SilentlyContinue
        Copy-Subset $pkgDir $destPkg @($p.keep)
        $files = (Get-ChildItem $destPkg -Recurse -File).Count
        Write-Ok "$files files"
    }

    # ── config ────────────────────────────────────────────────────────────
    Write-Step "Writing config"
    New-Item -ItemType Directory -Force -Path $out.Config | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $out.Config 'sessions') | Out-Null
    New-Item -ItemType Directory -Force -Path $out.Skills | Out-Null
    foreach ($d in @('npm-cache', 'node-cache', 'cache')) {
        New-Item -ItemType Directory -Force -Path (Join-Path $out.Temp $d) | Out-Null
    }

    foreach ($f in @('settings.json', 'models.json')) {
        $src = Join-Path $RepoRoot "config\pi\$f"
        $dst = Join-Path $out.Config $f
        if ((Test-Path $dst) -and -not $Force) { Write-Ok "$f kept (use -Force to overwrite)" }
        else { Copy-Item $src $dst -Force; Write-Ok "$f written" }
    }
    # AGENTS.md is repo-owned instruction content: always refreshed so an updated
    # rule set reaches an existing drive on the next build/update.
    Copy-Item (Join-Path $RepoRoot 'config\pi\AGENTS.md') (Join-Path $out.Config 'AGENTS.md') -Force
    Write-Ok 'AGENTS.md written'

    $authSrc = Join-Path $env:USERPROFILE '.pi\agent\auth.json'
    $authDst = Join-Path $out.Config 'auth.json'
    if (Test-Path $authDst) {
        Write-Ok "auth.json already on the drive (kept)"
    } elseif (Test-Path $authSrc) {
        Copy-Item $authSrc $authDst -Force
        Write-Ok "auth.json copied from $authSrc"
    } else {
        Write-Warn2 "no auth.json found on this host: run 'pi' once on the drive and use /login"
    }

    foreach ($e in @(@{ src = 'config\env.example.sh'; dst = 'config\env.sh' }, @{ src = 'config\env.example.bat'; dst = 'config\env.bat' })) {
        $dst = Join-Path $Target $e.dst
        if (-not (Test-Path $dst)) {
            if ($e.dst -like '*.bat') { Copy-TextCrlf (Join-Path $RepoRoot $e.src) $dst }
            else { Copy-Item (Join-Path $RepoRoot $e.src) $dst }
            Write-Ok "$($e.dst) created from template"
        }
    }

    # ── skills ────────────────────────────────────────────────────────────
    Write-Step "Copying $($M.skills.include.Count) whitelisted skills"
    $roots = @{
        agent  = Join-Path $env:USERPROFILE '.pi\agent'
        agents = Join-Path $env:USERPROFILE '.agents'
        npm    = Join-Path $env:USERPROFILE '.pi\agent\npm\node_modules'
    }
    foreach ($s in $M.skills.include) {
        $src = Join-Path $roots[$s.root] $s.path
        if (-not (Test-Path (Join-Path $src 'SKILL.md'))) { throw "skill source missing: $src" }
        $dst = Join-Path $out.Skills $s.name
        Remove-Item $dst -Recurse -Force -ErrorAction SilentlyContinue
        Copy-Item $src $dst -Recurse -Force
        Write-Ok "$($s.name)"
    }

    # ── launchers + docs ──────────────────────────────────────────────────
    Write-Step "Installing launchers and docs"
    foreach ($f in @('autorun.inf', 'README.md')) {
        Copy-Item (Join-Path $RepoRoot $f) (Join-Path $Target $f) -Force
    }
    Copy-TextCrlf (Join-Path $RepoRoot 'start.bat') (Join-Path $Target 'start.bat')
    Copy-TextLf (Join-Path $RepoRoot 'start.sh') (Join-Path $Target 'start.sh')

    $binDir = Join-Path $Target 'tools\bin'
    New-Item -ItemType Directory -Force -Path $binDir | Out-Null
    Copy-TextLf (Join-Path $RepoRoot 'scripts\shims\pi.sh') (Join-Path $binDir 'pi')
    Copy-TextCrlf (Join-Path $RepoRoot 'scripts\shims\pi.cmd') (Join-Path $binDir 'pi.cmd')
    Write-Ok "shims: tools/bin/pi, tools/bin/pi.cmd"
    New-Item -ItemType Directory -Force -Path (Join-Path $Target 'docs') | Out-Null
    Copy-Item (Join-Path $RepoRoot 'docs\scope.md') (Join-Path $Target 'docs\scope.md') -Force
    # ship the verifier so the drive can be checked from itself
    New-Item -ItemType Directory -Force -Path (Join-Path $Target 'scripts') | Out-Null
    Copy-Item (Join-Path $RepoRoot 'scripts\verify.ps1') (Join-Path $Target 'scripts\verify.ps1') -Force
    Copy-TextLf (Join-Path $RepoRoot 'scripts\verify.sh') (Join-Path $Target 'scripts\verify.sh')
    Copy-Item (Join-Path $RepoRoot 'scripts\update.ps1') (Join-Path $Target 'scripts\update.ps1') -Force
    Copy-TextLf (Join-Path $RepoRoot 'scripts\update.sh') (Join-Path $Target 'scripts\update.sh')
    Copy-Item (Join-Path $RepoRoot 'manifest.json') (Join-Path $Target 'manifest.json') -Force

    # ── portable git (windows only) ───────────────────────────────────────
    if ($M.git.enabled -and -not $SkipGit) {
        $g = $M.git.minGit
        $gitDir = Join-Path $Target $g.installDir
        if ((Test-Path (Join-Path $gitDir 'usr\bin\bash.exe')) -and -not $Force) {
            Write-Step "MinGit already present, skipping"
        } else {
            $zip = Join-Path $Staging $g.file
            Write-Step "Downloading MinGit $($g.version) (~$($g.sizeMb) MB)"
            Invoke-Download $g.url $zip
            Remove-Item $gitDir -Recurse -Force -ErrorAction SilentlyContinue
            New-Item -ItemType Directory -Force -Path $gitDir | Out-Null
            Write-Step "Extracting MinGit"
            # extract on NTFS then copy: bsdtar cannot restore the MinGit timestamps
            # directly on FAT/exFAT ("Can't restore time: Invalid argument")
            $stageGit = Join-Path $Staging 'mingit'
            Remove-Item $stageGit -Recurse -Force -ErrorAction SilentlyContinue
            Expand-ArchiveAny $zip $stageGit
            Copy-Item -Path (Join-Path $stageGit '*') -Destination $gitDir -Recurse -Force

            # MinGit ships sh.exe (which IS GNU bash) but not bash.exe, and pi looks
            # for bash.exe by name. Same binary, different argv[0].
            $sh = Join-Path $gitDir 'usr\bin\sh.exe'
            if (-not (Test-Path $sh)) { throw "MinGit layout unexpected: $sh missing" }
            Copy-Item $sh (Join-Path $gitDir 'usr\bin\bash.exe') -Force
            Write-Ok "bash: $gitDir\usr\bin\bash.exe (from sh.exe)"
        }
    } elseif (-not $SkipGit) {
        Write-Warn2 "git is disabled in the manifest, skipping"
    }

    # ── verify ────────────────────────────────────────────────────────────
    Write-Step "Verifying"
    $nodeExe = Join-Path $out.NodeWin 'node.exe'
    if (Test-Path $nodeExe) {
        $nv = & $nodeExe --version
        Write-Ok "portable node: $nv"
        $cli = Join-Path $nm '@earendil-works\pi-coding-agent\dist\bundle\cli.js'
        if (-not (Test-Path $cli)) { throw "pi entrypoint missing: $cli" }
        $env:PI_CODING_AGENT_DIR = $out.Config
        $env:PI_SKIP_VERSION_CHECK = '1'
        $env:PI_TELEMETRY = '0'
        $pv = & $nodeExe $cli --version
        Write-Ok "pi: $pv"
        if ($pv -notmatch '\d+\.\d+\.\d+') { throw "pi --version did not return a version" }
        Remove-Item Env:\PI_CODING_AGENT_DIR -ErrorAction SilentlyContinue

        if ($SmokeTest) {
            Write-Step "Smoke test (live model call)"
            $env:PI_CODING_AGENT_DIR = $out.Config
            $res = & $nodeExe $cli -p "Reply with exactly: PORTABLE-OK" --no-session 2>&1
            Remove-Item Env:\PI_CODING_AGENT_DIR -ErrorAction SilentlyContinue
            if (($res -join "`n") -notmatch 'PORTABLE-OK') { throw "smoke test failed: $($res -join ' | ')" }
            Write-Ok "model replied: PORTABLE-OK"
        }
    } else {
        Write-Warn2 "windows node not present, skipping runtime verification"
    }

    # ── flush + summary ───────────────────────────────────────────────────
    try { Write-VolumeCache -DriveLetter $drive -ErrorAction Stop; Write-Ok "volume cache flushed" }
    catch { Write-Warn2 "could not flush volume cache (needs elevation, harmless)" }

    Write-Step "Summary"
    $total = 0
    foreach ($part in @(
            @{ n = 'node win-x64'; p = $out.NodeWin },
            @{ n = 'node linux-x64'; p = $out.NodeLinux },
            @{ n = 'pi runtime'; p = $out.Runtime },
            @{ n = 'config/skills'; p = $out.Config },
            @{ n = 'portablegit'; p = (Join-Path $Target $M.git.minGit.installDir) })) {
        if (Test-Path $part.p) {
            $mb = [math]::Round(((Get-ChildItem $part.p -Recurse -File -ErrorAction SilentlyContinue | Measure-Object Length -Sum).Sum) / 1MB, 1)
            $fc = (Get-ChildItem $part.p -Recurse -File -ErrorAction SilentlyContinue).Count
            $total += $mb
            Write-Host ("    {0,-16} {1,8} MB {2,7} files" -f $part.n, $mb, $fc)
        }
    }
    Write-Host ("    {0,-16} {1,8} MB" -f 'TOTAL', [math]::Round($total, 1)) -ForegroundColor Green
    Write-Host ""
    Write-Host "Ready. Windows: double-click start.bat   |   Linux: bash start.sh" -ForegroundColor Green
}
finally {
    Remove-Item $Staging -Recurse -Force -ErrorAction SilentlyContinue
}
