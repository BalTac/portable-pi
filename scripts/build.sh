#!/usr/bin/env bash
# Build the portable-pi USB drive. Linux/macOS side (mirror of build.ps1).
#
#   bash scripts/build.sh /media/$USER/PORTABLE-PI
#   bash scripts/build.sh /tmp/usb-sim --skip-git --smoke
#
# Requirements: curl, tar, sha256sum (coreutils), node (to read manifest.json).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MANIFEST="$REPO/manifest.json"

TARGET=""
SKIP_GIT=0
SKIP_NODE=0
FORCE=0
SMOKE=0

while [ $# -gt 0 ]; do
    case "$1" in
        --skip-git) SKIP_GIT=1 ;;
        --skip-node) SKIP_NODE=1 ;;
        --force|-f) FORCE=1 ;;
        --smoke) SMOKE=1 ;;
        -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
        -*) echo "unknown option: $1" >&2; exit 2 ;;
        *) TARGET="$1" ;;
    esac
    shift
done

[ -n "$TARGET" ] || { echo "usage: bash scripts/build.sh /path/to/usb [--skip-git] [--force] [--smoke]" >&2; exit 2; }
[ -f "$MANIFEST" ] || { echo "manifest.json not found at $MANIFEST" >&2; exit 1; }
command -v node >/dev/null || { echo "node is required to read manifest.json" >&2; exit 1; }

step() { printf '==> %s\n' "$*"; }
ok()   { printf '    %s\n' "$*"; }
warn() { printf '    ! %s\n' "$*" >&2; }

jget() { node -e 'const m=require(process.argv[1]);console.log(eval(process.argv[2]))' "$MANIFEST" "$1"; }

# Effective skill whitelist: skills.local.json (gitignored) overrides the manifest.
SKILLS_FILE="$REPO/manifest.json"
[ -f "$REPO/skills.local.json" ] && SKILLS_FILE="$REPO/skills.local.json"
sget() { node -e 'const raw=require(process.argv[1]);const m=raw.skills?raw:{skills:raw};console.log(eval(process.argv[2]))' "$SKILLS_FILE" "$1"; }

NODE_VERSION="$(jget 'm.node.version')"
PI_VERSION="$(jget 'm.pi.version')"
RUNTIME_DIR="$(jget 'm.paths.runtimeDir')"
AGENT_DIR="$(jget 'm.paths.agentDir')"
SKILLS_DIR="$(jget 'm.paths.skillsDir')"
TEMP_DIR="$(jget 'm.paths.tempDir')"

[ -d "$TARGET" ] || { echo "Target '$TARGET' does not exist. Mount the USB drive first." >&2; exit 1; }
TARGET="$(cd "$TARGET" && pwd)"
STAGING="$(mktemp -d)"
trap 'rm -rf "$STAGING"' EXIT

step "Building portable-pi at $TARGET"
ok "node $NODE_VERSION | pi $PI_VERSION"

# ── helpers ─────────────────────────────────────────────────────────────
download() {
    curl -fsSL --retry 3 --connect-timeout 20 --progress-bar -o "$2" "$1"
}

extract_archive() { # file dest
    mkdir -p "$2"
    case "$1" in
        *.zip)
            command -v unzip >/dev/null || { echo "unzip is required to extract $1" >&2; exit 1; }
            unzip -q "$1" -d "$2"
            ;;
        *) tar -xf "$1" -C "$2" ;;
    esac
}

npm_tarball_url() { # name version
    node -e '
      const [name, version] = process.argv.slice(1);
      const base = name.startsWith("@") ? name.split("/")[1] : name;
      const scope = name.startsWith("@") ? encodeURIComponent(name) : name;
      console.log(`https://registry.npmjs.org/${scope}/-/${base}-${version}.tgz`);
    ' "$1" "$2"
}

verify_sha256() { # file shasums-file archive-name
    local expected
    expected="$(grep -E "[[:space:]]$3\$" "$2" | awk '{print $1}')"
    [ -n "$expected" ] || { echo "no checksum for $3" >&2; exit 1; }
    local actual
    actual="$(sha256sum "$1" | awk '{print $1}')"
    [ "$actual" = "$expected" ] || { echo "checksum mismatch for $3" >&2; exit 1; }
}

install_sh_wrapper() { # bin-dir name js-relative-path
    local path="$1/$2"
    rm -f "$path"
    cat > "$path" <<WRAP
#!/bin/sh
# generated by portable-pi: exFAT has no symlinks
self=\$0
case "\$self" in
  */*) ;;
  *) self=\$(command -v -- "\$self" 2>/dev/null || echo "\$self") ;;
esac
basedir=\$(cd -- "\$(dirname -- "\$self")" && pwd)
exec "\$basedir/node" "\$basedir/$3" "\$@"
WRAP
    chmod +x "$path" 2>/dev/null || true
}

# ── node ────────────────────────────────────────────────────────────────
if [ "$SKIP_NODE" = 0 ]; then
    SUMS="$STAGING/SHASUMS256.txt"
    download "$(jget "m.node.checksums.split('{version}').join(m.node.version)")" "$SUMS"

    COUNT="$(jget 'm.node.targets.length')"
    i=0
    while [ "$i" -lt "$COUNT" ]; do
        ID="$(jget "m.node.targets[$i].id")"
        URL="$(jget "m.node.targets[$i].url.split('{version}').join(m.node.version)")"
        ARCHIVE="$(jget "m.node.targets[$i].archive.split('{version}').join(m.node.version)")"
        INSTALL_REL="$(jget "m.node.targets[$i].installDir.split('{version}').join(m.node.version)")"
        NODE_BIN="$(jget "m.node.targets[$i].nodeBin")"
        DEST="$TARGET/$INSTALL_REL"

        if [ -e "$DEST/$NODE_BIN" ] && [ "$FORCE" = 0 ]; then
            step "node $ID already present, skipping"
        else
            step "Downloading $ARCHIVE"
            download "$URL" "$STAGING/$ARCHIVE"
            verify_sha256 "$STAGING/$ARCHIVE" "$SUMS" "$ARCHIVE"
            ok "sha256 ok"
            rm -rf "$STAGING/x-$ID" "$DEST"
            extract_archive "$STAGING/$ARCHIVE" "$STAGING/x-$ID"
            # FAT/exFAT cannot hold symlinks (bin/npm, bin/npx, bin/corepack): dereference
            find "$STAGING/x-$ID" -type l -print0 2>/dev/null | while IFS= read -r -d "" link; do
                target="$(readlink -f "$link" 2>/dev/null || true)"
                rm -f "$link"
                [ -n "$target" ] && [ -e "$target" ] && cp -RL "$target" "$link"
            done
            TOP="$(find "$STAGING/x-$ID" -mindepth 1 -maxdepth 1 -type d | head -1)"
            mkdir -p "$(dirname "$DEST")"
            mv "$TOP" "$DEST"
            ok "extracted to $DEST"
        fi

        if [ "$ID" = "linux-x64" ]; then
            install_sh_wrapper "$DEST/bin" npm '../lib/node_modules/npm/bin/npm-cli.js'
            install_sh_wrapper "$DEST/bin" npx '../lib/node_modules/npm/bin/npx-cli.js'
            install_sh_wrapper "$DEST/bin" corepack '../lib/node_modules/corepack/dist/corepack.js'
            ok "npm/npx/corepack rewritten as symlink-free sh wrappers"
        fi
        i=$((i + 1))
    done
else
    step "node download skipped (--skip-node)"
fi

# ── pi runtime ──────────────────────────────────────────────────────────
NM="$TARGET/$RUNTIME_DIR/node_modules"
mkdir -p "$NM"

# Extensions that spawn child pi processes load the *host* packages
# (pi-coding-agent dist/index.js, pi-agent-core, pi-ai, typebox). The bundled
# dist alone cannot satisfy them, so vendor that closure from this machine's pi
# installation into tools/pi/node_modules.
NEEDS_HOST_SDK="$(sget '(m.packages||(m.skills&&m.skills.packages)||[]).some(p=>p.requiresHostSdk)?"1":"0"')"
if [ "$NEEDS_HOST_SDK" = "1" ]; then
    step "Vendoring the host SDK closure (child pi processes)"
    HOST_ROOT=""
    for cand in "$HOME/.pi/agent/install/releases/$PI_VERSION/node_modules" "$HOME/.pi/agent/npm/node_modules"; do
        [ -f "$cand/@earendil-works/pi-coding-agent/package.json" ] && { HOST_ROOT="$cand"; break; }
    done
    [ -n "$HOST_ROOT" ] || { echo "requiresHostSdk: pi $PI_VERSION is not installed on this machine" >&2; exit 1; }
    printf '{"packages":[{"name":"@earendil-works/pi-coding-agent","spec":"npm:@earendil-works/pi-coding-agent@%s"}]}' "$PI_VERSION" > "$STAGING/host-sdk.json"
    node "$REPO/scripts/vendor-packages.mjs" --profile "$STAGING/host-sdk.json" --dest "$TARGET/$RUNTIME_DIR" \
        --host-packages "$HOST_ROOT" --allow-host-provided --force --json "$STAGING/host-sdk.report" \
        | grep -E 'MB|!' | sed 's/^/    /'
fi

COUNT="$(jget 'm.pi.runtimePackages.length')"
i=0
while [ "$i" -lt "$COUNT" ]; do
    NAME="$(jget "m.pi.runtimePackages[$i].name")"
    VERSION="$(jget "m.pi.runtimePackages[$i].version")"
    if [ "$NAME" = "@earendil-works/pi-coding-agent" ]; then VERSION="$PI_VERSION"; fi
    DEST="$NM/$NAME"

    if [ -e "$DEST" ] && [ "$FORCE" = 0 ]; then
        step "$NAME already present, skipping"
        i=$((i + 1)); continue
    fi

    step "Downloading $NAME@$VERSION"
    download "$(npm_tarball_url "$NAME" "$VERSION")" "$STAGING/pkg.tgz"
    rm -rf "$STAGING/pkg" "$DEST"
    mkdir -p "$STAGING/pkg" "$DEST"
    tar -xzf "$STAGING/pkg.tgz" -C "$STAGING/pkg"

    KEEP_COUNT="$(jget "m.pi.runtimePackages[$i].keep.length")"
    k=0
    while [ "$k" -lt "$KEEP_COUNT" ]; do
        ENTRY="$(jget "m.pi.runtimePackages[$i].keep[$k]")"
        if [ "$ENTRY" = "*" ]; then
            cp -R "$STAGING/pkg/package/." "$DEST/"
        else
            mkdir -p "$DEST/$(dirname "$ENTRY")"
            cp -R "$STAGING/pkg/package/$ENTRY" "$DEST/$ENTRY"
        fi
        k=$((k + 1))
    done
    ok "$(find "$DEST" -type f | wc -l | tr -d ' ') files"
    i=$((i + 1))
done

# ── config ──────────────────────────────────────────────────────────────
step "Writing config"
mkdir -p "$TARGET/$AGENT_DIR/sessions" "$TARGET/$SKILLS_DIR" \
         "$TARGET/$TEMP_DIR/npm-cache" "$TARGET/$TEMP_DIR/node-cache" "$TARGET/$TEMP_DIR/cache"

for f in settings.json models.json; do
    src="$REPO/config/pi/$f"; dst="$TARGET/$AGENT_DIR/$f"
    if [ -e "$dst" ] && [ "$FORCE" = 0 ]; then ok "$f kept (use --force to overwrite)"
    else cp "$src" "$dst"; ok "$f written"; fi
done
# AGENTS.md is repo-owned: always refreshed so an updated rule set reaches the drive
cp "$REPO/config/pi/AGENTS.md" "$TARGET/$AGENT_DIR/AGENTS.md"; ok "AGENTS.md written"

AUTH_SRC="${HOME}/.pi/agent/auth.json"
AUTH_DST="$TARGET/$AGENT_DIR/auth.json"
if [ -e "$AUTH_DST" ]; then
    ok "auth.json already on the drive (kept)"
elif [ -e "$AUTH_SRC" ]; then
    cp "$AUTH_SRC" "$AUTH_DST"; chmod 600 "$AUTH_DST" 2>/dev/null || true
    ok "auth.json copied from $AUTH_SRC"
else
    warn "no auth.json found: run pi on the drive once and use /login"
fi

[ -e "$TARGET/config/env.sh" ] || cp "$REPO/config/env.example.sh" "$TARGET/config/env.sh"
[ -e "$TARGET/config/env.bat" ] || cp "$REPO/config/env.example.bat" "$TARGET/config/env.bat"

# ── skills ──────────────────────────────────────────────────────────────
step "Copying $(sget 'skills.include.length') whitelisted skills"
# the drive mirrors the whitelist: drop anything else (pruned entries, hand-added folders).
# update only refreshes, it never deletes.
SKILLS_DIR_ON_DRIVE="$TARGET/$SKILLS_DIR"
if [ -d "$SKILLS_DIR_ON_DRIVE" ]; then
    for d in "$SKILLS_DIR_ON_DRIVE"/*/; do
        [ -d "$d" ] || continue
        name="$(basename "$d")"
        listed=0
        j=0; n="$(sget 'skills.include.length')"
        while [ "$j" -lt "$n" ]; do [ "$(sget "skills.include[$j].name")" = "$name" ] && listed=1; j=$((j + 1)); done
        [ "$listed" = 1 ] || { rm -rf "$d"; ok "pruned $name"; }
    done
fi
COUNT="$(sget 'skills.include.length')"
i=0
while [ "$i" -lt "$COUNT" ]; do
    NAME="$(sget "skills.include[$i].name")"
    ROOT="$(sget "skills.include[$i].root")"
    REL="$(sget "skills.include[$i].path")"
    case "$ROOT" in
        agent)  SRC="${HOME}/.pi/agent/$REL" ;;
        agents) SRC="${HOME}/.agents/$REL" ;;
        npm)    SRC="${HOME}/.pi/agent/npm/node_modules/$REL" ;;
        *) echo "unknown skill root: $ROOT" >&2; exit 1 ;;
    esac
    [ -f "$SRC/SKILL.md" ] || { echo "skill source missing: $SRC" >&2; exit 1; }
    rm -rf "$TARGET/$SKILLS_DIR/$NAME"
    cp -R "$SRC" "$TARGET/$SKILLS_DIR/$NAME"
    ok "$NAME"
    i=$((i + 1))
done

# ── third-party packages (vendored from this host, no install at run time) ─
PKG_COUNT="$(sget '(m.packages || (m.skills && m.skills.packages) || []).length')"
PKG_ROOT="$TARGET/$AGENT_DIR/packages"
if [ "$PKG_COUNT" != "0" ]; then
    step "Vendoring $PKG_COUNT third-party package(s) from this host"
    node "$REPO/scripts/vendor-packages.mjs" --profile "$SKILLS_FILE" --dest "$PKG_ROOT" --prune --json "$STAGING/packages.json"
    ok "vendored $(node -e 'const r=require(process.argv[1]);console.log(r.packages.length+" package(s), "+r.totalMb+" MB")' "$STAGING/packages.json")"
else
    [ -d "$PKG_ROOT" ] && { rm -rf "$PKG_ROOT"; ok "removed vendored packages (none in profile)"; }
    PKG_ROOT=""
fi

# package-provided skills: -ns disables package skill discovery, so the single
# --skill path the launcher passes must contain them too.
PKG_SKILLS=""
if [ "$PKG_COUNT" != "0" ]; then
    for sk in "$PKG_ROOT/node_modules"/*/skills/* "$PKG_ROOT/node_modules"/@*/*/skills/*; do
        [ -f "$sk/SKILL.md" ] || continue
        NAME="$(basename "$sk")"
        rm -rf "$TARGET/$SKILLS_DIR/$NAME"
        cp -R "$sk" "$TARGET/$SKILLS_DIR/$NAME"
        PKG_SKILLS="$PKG_SKILLS $NAME"
        ok "package skill $NAME"
    done
fi
node -e 'const fs=require("fs");fs.writeFileSync(process.argv[1],JSON.stringify(process.argv.slice(2)))' \
    "$STAGING/package-skills.json" $PKG_SKILLS

# settings.json: drive-relative package paths (survive a different letter/mount)
SETTINGS="$TARGET/$AGENT_DIR/settings.json"
if [ -f "$SETTINGS" ]; then
    node -e '
      const fs = require("fs");
      const [profilePath, settingsPath, pkgCount] = process.argv.slice(1);
      const raw = JSON.parse(fs.readFileSync(profilePath, "utf8"));
      const profile = raw.skills ? raw : { skills: raw };
      const s = JSON.parse(fs.readFileSync(settingsPath, "utf8"));
      const pkgs = Array.isArray(profile.packages) ? profile.packages : [];
      if (pkgs.length) s.packages = pkgs.map((p) => "./packages/node_modules/" + p.name);
      else delete s.packages;
      if (profile.settings && typeof profile.settings === "object") Object.assign(s, profile.settings);
      fs.writeFileSync(settingsPath, JSON.stringify(s, null, 2) + "\n");
      console.log("    settings.json merged (" + pkgs.length + " package entries)");
    ' "$SKILLS_FILE" "$SETTINGS" "$PKG_COUNT"
fi

# web-search.json: sanitized template only. SearXNG needs a self-hosted Python
# server, so it is deliberately absent; the owner adds API keys later.
if [ ! -f "$TARGET/$AGENT_DIR/web-search.json" ]; then
    cp "$REPO/config/pi/web-search.json" "$TARGET/$AGENT_DIR/web-search.json"
    ok "web-search.json written (provider auto, no SearXNG)"
else ok "web-search.json kept"; fi

# ── workspace (cwd of the launcher, home of the llm-wiki vault) ────────
step "Creating workspace"
mkdir -p "$TARGET/workspace"
[ -f "$TARGET/workspace/README.md" ] || cp "$REPO/docs/workspace.md" "$TARGET/workspace/README.md"
ok "workspace ready (WIKI_HOME=$TARGET/workspace)"

# ── launchers + docs ────────────────────────────────────────────────────
step "Installing launchers and docs"
cp "$REPO/start.sh" "$REPO/start.bat" "$REPO/autorun.inf" "$REPO/README.md" "$TARGET/"
cp "$REPO/update.sh" "$TARGET/update.sh"
# CRLF for the Windows launcher
node -e 'const fs=require("fs");const s=fs.readFileSync(process.argv[1],"utf8").replace(/
/g,"
").replace(/
/g,"
");fs.writeFileSync(process.argv[2],s)' "$REPO/update.bat" "$TARGET/update.bat"
cp "$REPO/llms.txt" "$REPO/NOTICE" "$REPO/skills.example.json" "$TARGET/"
mkdir -p "$TARGET/assets"
cp "$REPO/assets/banner.png" "$TARGET/assets/banner.png"
mkdir -p "$TARGET/tools/bin" "$TARGET/docs"
cp "$REPO/scripts/shims/pi.sh" "$TARGET/tools/bin/pi"
cp "$REPO/scripts/shims/pi.cmd" "$TARGET/tools/bin/pi.cmd"
chmod +x "$TARGET/tools/bin/pi" "$TARGET/start.sh" "$TARGET/update.sh" 2>/dev/null || true
cp "$REPO/scripts/fix-paths.js" "$TARGET/tools/bin/fix-paths.js"
printf '%s\n' "$TARGET/" > "$TARGET/config/drive-root.txt"
cp "$REPO/docs/scope.md" "$REPO/docs/manifest.schema.json" "$TARGET/docs/"
mkdir -p "$TARGET/scripts"
cp "$REPO/scripts/verify.ps1" "$REPO/scripts/verify.sh" "$REPO/scripts/update.ps1" "$REPO/scripts/update.sh" "$REPO/scripts/vendor-packages.mjs" "$REPO/scripts/check-updates.mjs" "$TARGET/scripts/"
chmod +x "$TARGET/scripts/verify.sh" "$TARGET/scripts/update.sh" 2>/dev/null || true
# the drive copy records the effective skill list, so update/verify can work from it
node -e '
  const fs=require("fs");
  const m=JSON.parse(fs.readFileSync(process.argv[1],"utf8"));
  const raw=JSON.parse(fs.readFileSync(process.argv[2],"utf8"));
  m.skills = raw.skills ? raw.skills : raw;
  const report = process.argv[4];
  const pkgSkills = process.argv[5];
  if (report && fs.existsSync(report)) m.packages = JSON.parse(fs.readFileSync(report,"utf8")).packages;
  else delete m.packages;
  m.packageSkills = (pkgSkills && fs.existsSync(pkgSkills)) ? JSON.parse(fs.readFileSync(pkgSkills,"utf8")) : [];
  fs.writeFileSync(process.argv[3], JSON.stringify(m,null,2)+"\n");
  console.log("    manifest.json written with "+m.skills.include.length+" skills, "+(m.packages?m.packages.length:0)+" packages");
' "$MANIFEST" "$SKILLS_FILE" "$TARGET/manifest.json" "$STAGING/packages.json" "$STAGING/package-skills.json"

# ── git (windows-only payload) ──────────────────────────────────────────
if [ "$SKIP_GIT" = 0 ]; then
    GIT_DIR_REL="$(jget 'm.git.minGit.installDir')"
    warn "MinGit is a Windows payload: skipped on a Linux build host (use --skip-git to silence)"
else
    step "git payload skipped"
fi

# ── verify ──────────────────────────────────────────────────────────────
step "Verifying"
CLI="$TARGET/$RUNTIME_DIR/node_modules/@earendil-works/pi-coding-agent/dist/bundle/cli.js"
[ -f "$CLI" ] || { echo "pi entrypoint missing: $CLI" >&2; exit 1; }

HOST_OS="$(uname -s)"
if [ "$HOST_OS" = "Linux" ]; then
    LINUX_NODE="$TARGET/$(jget "m.node.targets[1].installDir.split('{version}').join(m.node.version)")/bin/node"
    if [ -x "$LINUX_NODE" ]; then
        ok "portable node: $("$LINUX_NODE" --version)"
        out="$(PI_CODING_AGENT_DIR="$TARGET/$AGENT_DIR" PI_SKIP_VERSION_CHECK=1 PI_TELEMETRY=0 "$LINUX_NODE" "$CLI" --version)"
        ok "pi: $out"
        case "$out" in *[0-9].[0-9].[0-9]*) ;; *) echo "pi --version failed" >&2; exit 1 ;; esac
        if [ "$SMOKE" = 1 ]; then
            step "Smoke test (live model call)"
            res="$(PI_CODING_AGENT_DIR="$TARGET/$AGENT_DIR" PI_SKIP_VERSION_CHECK=1 PI_TELEMETRY=0 \
                   "$LINUX_NODE" "$CLI" -p "Reply with exactly: PORTABLE-OK" --no-session 2>&1 || true)"
            case "$res" in *PORTABLE-OK*) ok "model replied: PORTABLE-OK" ;;
                *) echo "smoke test failed: $res" >&2; exit 1 ;; esac
        fi
    else
        warn "$LINUX_NODE is not executable (exFAT mount without exec bit): remount with umask=000"
    fi
else
    warn "host is $HOST_OS: portable Linux node not executed here, only file checks done"
fi

sync 2>/dev/null || true

step "Summary"
du -sh "$TARGET/bin" "$TARGET/tools" "$TARGET/$AGENT_DIR" 2>/dev/null | sed 's/^/    /'
printf '    TOTAL %s\n' "$(du -sh "$TARGET" 2>/dev/null | cut -f1)"
echo
printf 'Ready. Windows: double-click start.bat   |   Linux: bash start.sh\n'
