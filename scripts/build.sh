#!/usr/bin/env bash
# Build the portable-pi USB drive. Linux/macOS side (mirror of build.ps1).
#
#   bash scripts/build.sh /media/$USER/PORTABLE-PI
#   bash scripts/build.sh /tmp/usb-sim --skip-git --smoke
#
# Requirements: curl, tar, sha256sum (coreutils), node (to read manifest.json).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MANIFEST="$REPO/manifest.json"

TARGET=""
SKIP_GIT=0
SKIP_NODE=0
FORCE=0
SMOKE=0

while [ $# -gt 0 ]; do
    case "$1" in
        --skip-git) SKIP_GIT=1 ;;
        --skip-node) SKIP_NODE=1 ;;
        --force|-f) FORCE=1 ;;
        --smoke) SMOKE=1 ;;
        -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
        -*) echo "unknown option: $1" >&2; exit 2 ;;
        *) TARGET="$1" ;;
    esac
    shift
done

[ -n "$TARGET" ] || { echo "usage: bash scripts/build.sh /path/to/usb [--skip-git] [--force] [--smoke]" >&2; exit 2; }
[ -f "$MANIFEST" ] || { echo "manifest.json not found at $MANIFEST" >&2; exit 1; }
command -v node >/dev/null || { echo "node is required to read manifest.json" >&2; exit 1; }

step() { printf '==> %s\n' "$*"; }
ok()   { printf '    %s\n' "$*"; }
warn() { printf '    ! %s\n' "$*" >&2; }

jget() { node -e 'const m=require(process.argv[1]);console.log(eval(process.argv[2]))' "$MANIFEST" "$1"; }

NODE_VERSION="$(jget 'm.node.version')"
PI_VERSION="$(jget 'm.pi.version')"
RUNTIME_DIR="$(jget 'm.paths.runtimeDir')"
AGENT_DIR="$(jget 'm.paths.agentDir')"
SKILLS_DIR="$(jget 'm.paths.skillsDir')"
TEMP_DIR="$(jget 'm.paths.tempDir')"

[ -d "$TARGET" ] || { echo "Target '$TARGET' does not exist. Mount the USB drive first." >&2; exit 1; }
TARGET="$(cd "$TARGET" && pwd)"
STAGING="$(mktemp -d)"
trap 'rm -rf "$STAGING"' EXIT

step "Building portable-pi at $TARGET"
ok "node $NODE_VERSION | pi $PI_VERSION"

# ── helpers ─────────────────────────────────────────────────────────────
download() {
    curl -fsSL --retry 3 --connect-timeout 20 --progress-bar -o "$2" "$1"
}

extract_archive() { # file dest
    mkdir -p "$2"
    case "$1" in
        *.zip)
            command -v unzip >/dev/null || { echo "unzip is required to extract $1" >&2; exit 1; }
            unzip -q "$1" -d "$2"
            ;;
        *) tar -xf "$1" -C "$2" ;;
    esac
}

npm_tarball_url() { # name version
    node -e '
      const [name, version] = process.argv.slice(1);
      const base = name.startsWith("@") ? name.split("/")[1] : name;
      const scope = name.startsWith("@") ? encodeURIComponent(name) : name;
      console.log(`https://registry.npmjs.org/${scope}/-/${base}-${version}.tgz`);
    ' "$1" "$2"
}

verify_sha256() { # file shasums-file archive-name
    local expected
    expected="$(grep -E "[[:space:]]$3\$" "$2" | awk '{print $1}')"
    [ -n "$expected" ] || { echo "no checksum for $3" >&2; exit 1; }
    local actual
    actual="$(sha256sum "$1" | awk '{print $1}')"
    [ "$actual" = "$expected" ] || { echo "checksum mismatch for $3" >&2; exit 1; }
}

install_sh_wrapper() { # bin-dir name js-relative-path
    local path="$1/$2"
    rm -f "$path"
    cat > "$path" <<WRAP
#!/bin/sh
# generated by portable-pi: exFAT has no symlinks
self=\$0
case "\$self" in
  */*) ;;
  *) self=\$(command -v -- "\$self" 2>/dev/null || echo "\$self") ;;
esac
basedir=\$(cd -- "\$(dirname -- "\$self")" && pwd)
exec "\$basedir/node" "\$basedir/$3" "\$@"
WRAP
    chmod +x "$path" 2>/dev/null || true
}

# ── node ────────────────────────────────────────────────────────────────
if [ "$SKIP_NODE" = 0 ]; then
    SUMS="$STAGING/SHASUMS256.txt"
    download "$(jget "m.node.checksums.split('{version}').join(m.node.version)")" "$SUMS"

    COUNT="$(jget 'm.node.targets.length')"
    i=0
    while [ "$i" -lt "$COUNT" ]; do
        ID="$(jget "m.node.targets[$i].id")"
        URL="$(jget "m.node.targets[$i].url.split('{version}').join(m.node.version)")"
        ARCHIVE="$(jget "m.node.targets[$i].archive.split('{version}').join(m.node.version)")"
        INSTALL_REL="$(jget "m.node.targets[$i].installDir.split('{version}').join(m.node.version)")"
        NODE_BIN="$(jget "m.node.targets[$i].nodeBin")"
        DEST="$TARGET/$INSTALL_REL"

        if [ -e "$DEST/$NODE_BIN" ] && [ "$FORCE" = 0 ]; then
            step "node $ID already present, skipping"
        else
            step "Downloading $ARCHIVE"
            download "$URL" "$STAGING/$ARCHIVE"
            verify_sha256 "$STAGING/$ARCHIVE" "$SUMS" "$ARCHIVE"
            ok "sha256 ok"
            rm -rf "$STAGING/x-$ID" "$DEST"
            extract_archive "$STAGING/$ARCHIVE" "$STAGING/x-$ID"
            TOP="$(find "$STAGING/x-$ID" -mindepth 1 -maxdepth 1 -type d | head -1)"
            mkdir -p "$(dirname "$DEST")"
            mv "$TOP" "$DEST"
            ok "extracted to $DEST"
        fi

        if [ "$ID" = "linux-x64" ]; then
            install_sh_wrapper "$DEST/bin" npm '../lib/node_modules/npm/bin/npm-cli.js'
            install_sh_wrapper "$DEST/bin" npx '../lib/node_modules/npm/bin/npx-cli.js'
            install_sh_wrapper "$DEST/bin" corepack '../lib/node_modules/corepack/dist/corepack.js'
            ok "npm/npx/corepack rewritten as symlink-free sh wrappers"
        fi
        i=$((i + 1))
    done
else
    step "node download skipped (--skip-node)"
fi

# ── pi runtime ──────────────────────────────────────────────────────────
NM="$TARGET/$RUNTIME_DIR/node_modules"
mkdir -p "$NM"

COUNT="$(jget 'm.pi.runtimePackages.length')"
i=0
while [ "$i" -lt "$COUNT" ]; do
    NAME="$(jget "m.pi.runtimePackages[$i].name")"
    VERSION="$(jget "m.pi.runtimePackages[$i].version")"
    if [ "$NAME" = "@earendil-works/pi-coding-agent" ]; then VERSION="$PI_VERSION"; fi
    DEST="$NM/$NAME"

    if [ -e "$DEST" ] && [ "$FORCE" = 0 ]; then
        step "$NAME already present, skipping"
        i=$((i + 1)); continue
    fi

    step "Downloading $NAME@$VERSION"
    download "$(npm_tarball_url "$NAME" "$VERSION")" "$STAGING/pkg.tgz"
    rm -rf "$STAGING/pkg" "$DEST"
    mkdir -p "$STAGING/pkg" "$DEST"
    tar -xzf "$STAGING/pkg.tgz" -C "$STAGING/pkg"

    KEEP_COUNT="$(jget "m.pi.runtimePackages[$i].keep.length")"
    k=0
    while [ "$k" -lt "$KEEP_COUNT" ]; do
        ENTRY="$(jget "m.pi.runtimePackages[$i].keep[$k]")"
        if [ "$ENTRY" = "*" ]; then
            cp -R "$STAGING/pkg/package/." "$DEST/"
        else
            mkdir -p "$DEST/$(dirname "$ENTRY")"
            cp -R "$STAGING/pkg/package/$ENTRY" "$DEST/$ENTRY"
        fi
        k=$((k + 1))
    done
    ok "$(find "$DEST" -type f | wc -l | tr -d ' ') files"
    i=$((i + 1))
done

# ── config ──────────────────────────────────────────────────────────────
step "Writing config"
mkdir -p "$TARGET/$AGENT_DIR/sessions" "$TARGET/$SKILLS_DIR" \
         "$TARGET/$TEMP_DIR/npm-cache" "$TARGET/$TEMP_DIR/node-cache" "$TARGET/$TEMP_DIR/cache"

for f in settings.json models.json AGENTS.md; do
    src="$REPO/config/pi/$f"; dst="$TARGET/$AGENT_DIR/$f"
    if [ -e "$dst" ] && [ "$FORCE" = 0 ]; then ok "$f kept (use --force to overwrite)"
    else cp "$src" "$dst"; ok "$f written"; fi
done

AUTH_SRC="${HOME}/.pi/agent/auth.json"
AUTH_DST="$TARGET/$AGENT_DIR/auth.json"
if [ -e "$AUTH_DST" ]; then
    ok "auth.json already on the drive (kept)"
elif [ -e "$AUTH_SRC" ]; then
    cp "$AUTH_SRC" "$AUTH_DST"; chmod 600 "$AUTH_DST" 2>/dev/null || true
    ok "auth.json copied from $AUTH_SRC"
else
    warn "no auth.json found: run pi on the drive once and use /login"
fi

[ -e "$TARGET/config/env.sh" ] || cp "$REPO/config/env.example.sh" "$TARGET/config/env.sh"
[ -e "$TARGET/config/env.bat" ] || cp "$REPO/config/env.example.bat" "$TARGET/config/env.bat"

# ── skills ──────────────────────────────────────────────────────────────
step "Copying $(jget 'm.skills.include.length') whitelisted skills"
COUNT="$(jget 'm.skills.include.length')"
i=0
while [ "$i" -lt "$COUNT" ]; do
    NAME="$(jget "m.skills.include[$i].name")"
    ROOT="$(jget "m.skills.include[$i].root")"
    REL="$(jget "m.skills.include[$i].path")"
    case "$ROOT" in
        agent)  SRC="${HOME}/.pi/agent/$REL" ;;
        agents) SRC="${HOME}/.agents/$REL" ;;
        npm)    SRC="${HOME}/.pi/agent/npm/node_modules/$REL" ;;
        *) echo "unknown skill root: $ROOT" >&2; exit 1 ;;
    esac
    [ -f "$SRC/SKILL.md" ] || { echo "skill source missing: $SRC" >&2; exit 1; }
    rm -rf "$TARGET/$SKILLS_DIR/$NAME"
    cp -R "$SRC" "$TARGET/$SKILLS_DIR/$NAME"
    ok "$NAME"
    i=$((i + 1))
done

# ── launchers + docs ────────────────────────────────────────────────────
step "Installing launchers and docs"
cp "$REPO/start.sh" "$REPO/start.bat" "$REPO/autorun.inf" "$REPO/README.md" "$TARGET/"
mkdir -p "$TARGET/tools/bin" "$TARGET/docs"
cp "$REPO/scripts/shims/pi.sh" "$TARGET/tools/bin/pi"
cp "$REPO/scripts/shims/pi.cmd" "$TARGET/tools/bin/pi.cmd"
chmod +x "$TARGET/tools/bin/pi" "$TARGET/start.sh" 2>/dev/null || true
cp "$REPO/docs/scope.md" "$TARGET/docs/scope.md"
cp "$MANIFEST" "$TARGET/manifest.json"

# ── git (windows-only payload) ──────────────────────────────────────────
if [ "$SKIP_GIT" = 0 ]; then
    GIT_DIR_REL="$(jget 'm.git.minGit.installDir')"
    warn "MinGit is a Windows payload: skipped on a Linux build host (use --skip-git to silence)"
else
    step "git payload skipped"
fi

# ── verify ──────────────────────────────────────────────────────────────
step "Verifying"
CLI="$TARGET/$RUNTIME_DIR/node_modules/@earendil-works/pi-coding-agent/dist/bundle/cli.js"
[ -f "$CLI" ] || { echo "pi entrypoint missing: $CLI" >&2; exit 1; }

HOST_OS="$(uname -s)"
if [ "$HOST_OS" = "Linux" ]; then
    LINUX_NODE="$TARGET/$(jget "m.node.targets[1].installDir.split('{version}').join(m.node.version)")/bin/node"
    if [ -x "$LINUX_NODE" ]; then
        ok "portable node: $("$LINUX_NODE" --version)"
        out="$(PI_CODING_AGENT_DIR="$TARGET/$AGENT_DIR" PI_SKIP_VERSION_CHECK=1 PI_TELEMETRY=0 "$LINUX_NODE" "$CLI" --version)"
        ok "pi: $out"
        case "$out" in *[0-9].[0-9].[0-9]*) ;; *) echo "pi --version failed" >&2; exit 1 ;; esac
        if [ "$SMOKE" = 1 ]; then
            step "Smoke test (live model call)"
            res="$(PI_CODING_AGENT_DIR="$TARGET/$AGENT_DIR" PI_SKIP_VERSION_CHECK=1 PI_TELEMETRY=0 \
                   "$LINUX_NODE" "$CLI" -p "Reply with exactly: PORTABLE-OK" --no-session 2>&1 || true)"
            case "$res" in *PORTABLE-OK*) ok "model replied: PORTABLE-OK" ;;
                *) echo "smoke test failed: $res" >&2; exit 1 ;; esac
        fi
    else
        warn "$LINUX_NODE is not executable (exFAT mount without exec bit): remount with umask=000"
    fi
else
    warn "host is $HOST_OS: portable Linux node not executed here, only file checks done"
fi

sync 2>/dev/null || true

step "Summary"
du -sh "$TARGET/bin" "$TARGET/tools" "$TARGET/$AGENT_DIR" 2>/dev/null | sed 's/^/    /'
printf '    TOTAL %s\n' "$(du -sh "$TARGET" 2>/dev/null | cut -f1)"
echo
printf 'Ready. Windows: double-click start.bat   |   Linux: bash start.sh\n'
